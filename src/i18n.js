function getInitialLang() {
  if (typeof window !== 'undefined') {
    try {
      const saved = window.localStorage?.getItem('whyline-lang');
      if (saved === 'en' || saved === 'te' || saved === 'hi') {
        return saved;
      }
    } catch {
      // Ignore storage error
    }
  }
  return 'en';
}

const I18nContext = createContext({
  lang: 'en',
  setLang: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(getInitialLang);

  const setLang = (nextLang) => {
    const normalized = fromBcp47(nextLang);
    setLangState(normalized);
    if (typeof window !== 'undefined') {
      try {
        window.localStorage?.setItem('whyline-lang', normalized);
      } catch {
        // Ignore storage error
      }
    }
  };

  const t = (key) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  };

  return React.createElement(I18nContext.Provider, { value: { lang, setLang, t } }, children);
}

export function useI18n() {
  return useContext(I18nContext);
}
